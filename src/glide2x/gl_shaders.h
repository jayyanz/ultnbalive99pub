static const char k_hlsl_main[] =
"cbuffer CB : register(b0) {\n"
"  float4 vp; uint4 cc; uint4 ac; uint4 inv; uint4 t0c; uint4 t1c; uint4 tinv;\n"
"  uint4 tex0; uint4 tex1; uint4 tsamp; uint4 tclamp; float4 stScale; float4 lodBias;\n"
"  float4 constColor; uint4 at; float4 fogColor; float4 misc;\n"
"};\n"
"Texture2D<float4> T0  : register(t0);\n"
"Texture2D<uint2>  T0i : register(t1);\n"
"Texture2D<float4> T1  : register(t2);\n"
"Texture2D<uint2>  T1i : register(t3);\n"
"Texture2D<float4> PAL : register(t4);\n"
"SamplerState S0 : register(s0);\n"
"SamplerState S1 : register(s1);\n"
"struct VI { float4 p : POSITION; float4 c : COLOR; float4 st : TEXCOORD0; float4 w : TEXCOORD1; float2 q : TEXCOORD2; };\n"
"struct VO {\n"
"  float4 pos : SV_Position;\n"
"  noperspective float4 c : COLOR;\n"
"  noperspective float4 st : TEXCOORD0;\n"
"  noperspective float4 zw : TEXCOORD1;   /* ooz, oow, oow0, oow1 */\n"
"  nointerpolation float4 misc : TEXCOORD2; /* bias, pal0, pal1 */\n"
"};\n"
"VO vs_main(VI i) {\n"
"  VO o;\n"
"  o.pos = float4(i.p.x * vp.x - 1.0, i.p.y * vp.y + 1.0, 0.5, 1.0);\n"
"  o.c = i.c / 255.0;\n"
"  o.st = i.st;\n"
"  o.zw = float4(i.p.z, i.p.w, i.w.x, i.w.y);\n"
"  o.misc = float4(i.w.z, i.w.w, i.q.x, 0);\n"
"  return o;\n"
"}\n"
"int wrapc(int i, int n, uint clampit) { return clampit ? clamp(i, 0, n - 1) : ((i % n) + n) % n; }\n"
"float4 palFetch(Texture2D<uint2> T, int2 xy, int lvl, uint kind, float row) {\n"
"  uint2 v = T.Load(int3(xy, lvl));\n"
"  float4 c = PAL.Load(int3((int)v.x, (int)row, 0));\n"
"  c.a = (kind == 3) ? v.y / 255.0 : 1.0;\n"
"  return c;\n"
"}\n"
"float4 samplePal(Texture2D<uint2> T, float2 uv, float2 dx, float2 dy, uint4 tex, uint filt, uint mip,\n"
"                 uint2 cl, float lodb, float row) {\n"
"  float2 sz = float2(tex.y, tex.z);\n"
"  int L = 0;\n"
"  if (mip != 0 && tex.w > 1) {\n"
"    float2 a = dx * sz, b = dy * sz;\n"
"    float rho = max(dot(a, a), dot(b, b));\n"
"    float lv = 0.5 * log2(max(rho, 1e-12)) + lodb;\n"
"    L = (int)clamp(floor(lv + 0.5), 0, (float)tex.w - 1);\n"
"  }\n"
"  int lw = max((int)tex.y >> L, 1), lh = max((int)tex.z >> L, 1);\n"
"  float2 p = uv * float2(lw, lh);\n"
"  if (filt == 0) {\n"
"    int2 i = (int2)floor(p);\n"
"    return palFetch(T, int2(wrapc(i.x, lw, cl.x), wrapc(i.y, lh, cl.y)), L, tex.x, row);\n"
"  }\n"
"  p -= 0.5;\n"
"  float2 fl = floor(p); float2 f = p - fl; int2 i0 = (int2)fl;\n"
"  int x0 = wrapc(i0.x, lw, cl.x), x1 = wrapc(i0.x + 1, lw, cl.x);\n"
"  int y0 = wrapc(i0.y, lh, cl.y), y1 = wrapc(i0.y + 1, lh, cl.y);\n"
"  float4 c00 = palFetch(T, int2(x0, y0), L, tex.x, row), c10 = palFetch(T, int2(x1, y0), L, tex.x, row);\n"
"  float4 c01 = palFetch(T, int2(x0, y1), L, tex.x, row), c11 = palFetch(T, int2(x1, y1), L, tex.x, row);\n"
"  return lerp(lerp(c00, c10, f.x), lerp(c01, c11, f.x), f.y);\n"
"}\n"
"float3 comb3(uint fn, float3 f, float3 l, float la, float3 o) {\n"
"  if (fn == 0) return 0;\n"
"  if (fn == 1) return l;\n"
"  if (fn == 2) return la;\n"
"  if (fn == 3) return f * o;\n"
"  if (fn == 4) return f * o + l;\n"
"  if (fn == 5) return f * o + la;\n"
"  if (fn == 6) return f * (o - l);\n"
"  if (fn == 7) return f * (o - l) + l;\n"
"  if (fn == 8) return f * (o - l) + la;\n"
"  if (fn == 9) return f * (-l) + l;\n"
"  if (fn == 16) return f * (-l) + la;\n"
"  return l;\n"
"}\n"
"float comb1(uint fn, float f, float l, float o) { return comb3(fn, f.xxx, l.xxx, l, o.xxx).x; }\n"
"/* texture unit combine: local = texel, other = upstream unit */\n"
"float4 tmuComb(uint4 c, uint rinv, uint ainv, float4 l, float4 o) {\n"
"  float3 fr; float fa;\n"
"  uint k = c.y;\n"
"  fr = (k == 0) ? 0 : (k == 1) ? l.rgb : (k == 2) ? o.aaa : (k == 3) ? l.aaa : (k == 8) ? 1 :\n"
"       (k == 9) ? 1 - l.rgb : (k == 10) ? 1 - o.aaa : (k == 11) ? 1 - l.aaa : (k == 12 || k == 13) ? 1 : 0;\n"
"  k = c.w;\n"
"  fa = (k == 0) ? 0 : (k == 1) ? l.a : (k == 2) ? o.a : (k == 3) ? l.a : (k == 8) ? 1 :\n"
"       (k == 9) ? 1 - l.a : (k == 10) ? 1 - o.a : (k == 11) ? 1 - l.a : (k == 12 || k == 13) ? 1 : 0;\n"
"  float4 r = float4(comb3(c.x, fr, l.rgb, l.a, o.rgb), comb1(c.z, fa, l.a, o.a));\n"
"  if (rinv) r.rgb = 1 - r.rgb;\n"
"  if (ainv) r.a = 1 - r.a;\n"
"  return saturate(r);\n"
"}\n"
"bool cmp8(uint f, uint a, uint r) {\n"
"  if (f == 0) return false; if (f == 1) return a < r; if (f == 2) return a == r; if (f == 3) return a <= r;\n"
"  if (f == 4) return a > r; if (f == 5) return a != r; if (f == 6) return a >= r; return true;\n"
"}\n"
"struct PO { float4 c : SV_Target; float d : SV_Depth; };\n"
"PO ps_main(VO i) {\n"
"  PO o;\n"
"  float4 it = saturate(i.c);\n"
"  float q0 = (abs(i.zw.z) < 1e-12) ? 1e-12 : i.zw.z, q1 = (abs(i.zw.w) < 1e-12) ? 1e-12 : i.zw.w;\n"
"  float2 uv0 = i.st.xy / q0 * stScale.xy;\n"
"  float2 uv1 = i.st.zw / q1 * stScale.zw;\n"
"  float2 dx0 = ddx(uv0), dy0 = ddy(uv0), dx1 = ddx(uv1), dy1 = ddy(uv1);\n"
"  float4 tx1 = 0, tx0 = 0;\n"
"  if (tex1.x == 1) tx1 = T1.SampleGrad(S1, uv1, dx1, dy1);\n"
"  else if (tex1.x >= 2) tx1 = samplePal(T1i, uv1, dx1, dy1, tex1, tsamp.z, tsamp.w, tclamp.zw, lodBias.y, i.misc.z);\n"
"  if (tex1.x != 0) tx1 = tmuComb(t1c, tinv.z, tinv.w, tx1, float4(0, 0, 0, 0));\n"
"  if (tex0.x == 1) tx0 = T0.SampleGrad(S0, uv0, dx0, dy0);\n"
"  else if (tex0.x >= 2) tx0 = samplePal(T0i, uv0, dx0, dy0, tex0, tsamp.x, tsamp.y, tclamp.xy, lodBias.x, i.misc.y);\n"
"  float4 tex = (tex0.x != 0) ? tmuComb(t0c, tinv.x, tinv.y, tx0, tx1) : tx1;\n"
"  /* colour and alpha combine */\n"
"  float3 lrgb = (cc.z == 1) ? constColor.rgb : it.rgb;\n"
"  float3 orgb = (cc.w == 0) ? it.rgb : (cc.w == 1) ? tex.rgb : constColor.rgb;\n"
"  float la = (ac.z == 1) ? constColor.a : (ac.z == 2) ? saturate(i.zw.x / 65535.0) : it.a;\n"
"  float oa = (ac.w == 0) ? it.a : (ac.w == 1) ? tex.a : constColor.a;\n"
"  uint k = cc.y;\n"
"  float3 fr = (k == 0) ? 0 : (k == 1) ? lrgb : (k == 2) ? oa.xxx : (k == 3) ? la.xxx : (k == 4) ? tex.aaa : (k == 8) ? 1 :\n"
"              (k == 9) ? 1 - lrgb : (k == 10) ? 1 - oa.xxx : (k == 11) ? 1 - la.xxx : (k == 12) ? 1 - tex.aaa : (k == 13) ? 1 : 0;\n"
"  k = ac.y;\n"
"  float fa = (k == 0) ? 0 : (k == 1) ? la : (k == 2) ? oa : (k == 3) ? la : (k == 4) ? tex.a : (k == 8) ? 1 :\n"
"             (k == 9) ? 1 - la : (k == 10) ? 1 - oa : (k == 11) ? 1 - la : (k == 12) ? 1 - tex.a : (k == 13) ? 1 : 0;\n"
"  float3 rgb = comb3(cc.x, fr, lrgb, la, orgb);\n"
"  float a = comb1(ac.x, fa, la, oa);\n"
"  if (inv.x) rgb = 1 - rgb;\n"
"  if (inv.y) a = 1 - a;\n"
"  rgb = saturate(rgb); a = saturate(a);\n"
"  if (!cmp8(at.x, (uint)round(a * 255.0), at.y)) discard;\n"
"  if (at.z) {\n"
"    uint3 c8 = (uint3)round(rgb * 255.0);\n"
"    if (((c8.r << 16) | (c8.g << 8) | c8.b) == at.w) discard;\n"
"  }\n"
"  o.c = float4(rgb, a);\n"
"  /* depth: same units as the Voodoo's 16-bit depth buffer, plus the bias level */\n"
"  float v = 65535.0;\n"
"  if (inv.z == 1 || inv.z == 3) v = i.zw.x;\n"
"  else if (inv.z == 2 || inv.z == 4) {\n"
"    float w = 1.0 / max(i.zw.y, 1e-12);\n"
"    if (w < 1.0) v = 0; else { float e = min(floor(log2(w)), 15.0); v = e * 4096.0 + (w / exp2(e) - 1.0) * 4096.0; }\n"
"  }\n"
"  o.d = saturate((v + i.misc.x) / 65535.0);\n"
"  return o;\n"
"}\n";

