"""Generate gl_stubs.cpp and glide2x.def for the glide2x wrapper.

Reads glide2x_exports.txt (decorated names, e.g. _grDrawTriangle@12) and the
implemented functions in gl_api.cpp (declared "... GAPI name("). Every export
without an implementation gets a stub that logs its first call and returns 0.
"""
import pathlib, re, sys

here = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '.')
names = [l.strip() for l in (here / 'glide2x_exports.txt').read_text().splitlines() if l.strip()]
impl = set(re.findall(r'\bGAPI\s+(\w+)\s*\(', (here / 'gl_api.cpp').read_text()))

out = ['/* Generated by tools/gen_glide_stubs.py. Do not edit. */',
       '#include "gl_internal.h"', '']
stubs = 0
for n in names:
    base, args = n[1:].rsplit('@', 1)
    if base in impl:
        continue
    nargs = int(args) // 4
    params = ', '.join('FxU32 a%d' % i for i in range(nargs)) or 'void'
    unused = ' '.join('(void)a%d;' % i for i in range(nargs))
    out += ['extern "C" FxU32 GAPI %s(%s)' % (base, params), '{',
            '    static int logged;', '    %s' % unused if unused else '',
            '    if (!logged++) glog("%s called (not implemented, returns 0)");' % base,
            '    return 0;', '}', '']
    stubs += 1
(here / 'gl_stubs.cpp').write_text('\n'.join(out) + '\n')

d = ['LIBRARY glide2x.dll', 'EXPORTS']
d += ['    %s=%s' % (n, n[1:]) for n in names]
(here / 'glide2x.def').write_text('\n'.join(d) + '\n')
print('%d exports, %d implemented, %d stubs' % (len(names), len(names) - stubs, stubs))
