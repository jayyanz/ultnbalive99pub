"""Generate logging thunks and a .def file for the glide2x.dll proxy.

Input: glide2x_exports.txt, one decorated stdcall name per line (e.g. _grGlideInit@0).
The first 54 are the functions NBAWIN.EXE v1.1 uses; the rest complete the Glide 2.60
export set (taken from dgVoodoo 2.86.5 Glide2x.dll) so other modules that link to
glide2x.dll, such as the 3dfx splash screen DLL 3DfxSpl2.dll, still resolve.
Output: glide_thunks.inc (C) and glide2x.def.
"""
import sys, pathlib

here = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '.')
names = [l.strip() for l in (here / 'glide2x_exports.txt').read_text().splitlines() if l.strip()]

c = ['/* Generated by tools/gen_glide_thunks.py. Do not edit. */',
     '#define GLIDE_FN_COUNT %d' % len(names), '',
     'static const char *const g_fn_name[GLIDE_FN_COUNT] = {']
c += ['    "%s",' % n for n in names]
c += ['};', '', 'static const int g_fn_argbytes[GLIDE_FN_COUNT] = {']
c += ['    %s,' % n.rsplit('@', 1)[1] for n in names]
c += ['};', '', '__asm__(".text\\n"']
for i, n in enumerate(names):
    c += ['    ".globl _thunk_%d\\n"' % i,
          '    "_thunk_%d:\\n"' % i,
          '    "  pushal\\n"',
          '    "  leal 32(%%esp), %%eax\\n"',
          '    "  pushl %%eax\\n"',
          '    "  pushl $%d\\n"' % i,
          '    "  call _glog_call\\n"',
          '    "  addl $8, %%esp\\n"',
          '    "  popal\\n"',
          '    "  jmp *_g_real+%d\\n"' % (4 * i)]
c += [');', '']
(here / 'glide_thunks.inc').write_text('\n'.join(c).replace('%%', '%') + '\n')

d = ['LIBRARY glide2x.dll', 'EXPORTS']
d += ['    %s=thunk_%d @%d' % (n, i, i + 1) for i, n in enumerate(names)]
(here / 'glide2x.def').write_text('\n'.join(d) + '\n')
print('generated', len(names), 'thunks')
