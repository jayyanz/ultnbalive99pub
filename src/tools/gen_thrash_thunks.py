"""Generate the call thunks and .def file for thrash_log (3rash\\voodoologa.dll).

Input: thrash_exports.txt, the 34 decorated stdcall names every NBA Live 99 THRASH
driver exports (same list in VOODOOA, D3DA, RAGEA and SOFTTRIA).
Output: thrash_thunks.inc (C, with GNU asm) and thrash.def.

Each thunk logs the call (arguments and caller), calls the real driver with the
same stack, logs the result and returns to the game. The game's return address
is kept on a small per-thread stack in thrash_log.cpp while the real call runs.
"""
import sys, pathlib

here = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '.')
names = [l.strip() for l in (here / 'thrash_exports.txt').read_text().splitlines() if l.strip()]

c = ['/* Generated by tools/gen_thrash_thunks.py. Do not edit. */',
     '#define THRASH_FN_COUNT %d' % len(names), '',
     'static const char *const g_fn_name[THRASH_FN_COUNT] = {']
c += ['    "%s",' % n for n in names]
c += ['};', '', 'static const int g_fn_argbytes[THRASH_FN_COUNT] = {']
c += ['    %s,' % n.rsplit('@', 1)[1] for n in names]
c += ['};', '', '__asm__(".text\\n"']
for i, n in enumerate(names):
    c += ['    ".globl _tthunk_%d\\n"' % i,
          '    "_tthunk_%d:\\n"' % i,
          # log the call: stack[0] = game's return address, stack[1..] = arguments
          '    "  pushal\\n"',
          '    "  leal 32(%%esp), %%eax\\n"',
          '    "  pushl %%eax\\n"',
          '    "  pushl $%d\\n"' % i,
          '    "  call _tl_enter\\n"',
          '    "  addl $8, %%esp\\n"',
          '    "  popal\\n"',
          # keep the return address, call the real driver with the same arguments
          '    "  addl $4, %%esp\\n"',
          '    "  call *_g_real+%d\\n"' % (4 * i),
          # log the result and go back to the game
          '    "  pushl %%eax\\n"',
          '    "  pushal\\n"',
          '    "  pushl %%eax\\n"',
          '    "  pushl $%d\\n"' % i,
          '    "  call _tl_leave\\n"',
          '    "  addl $8, %%esp\\n"',
          '    "  movl %%eax, 32(%%esp)\\n"',
          '    "  popal\\n"',
          '    "  ret\\n"']
c += [');', '']
(here / 'thrash_thunks.inc').write_text('\n'.join(c).replace('%%', '%') + '\n')

d = ['LIBRARY voodoologa.dll', 'EXPORTS']
d += ['    %s=tthunk_%d @%d' % (n, i, i + 1) for i, n in enumerate(names)]
(here / 'thrash.def').write_text('\n'.join(d) + '\n')
print('generated', len(names), 'thrash thunks')
