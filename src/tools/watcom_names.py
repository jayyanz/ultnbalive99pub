"""Function names from NBAWIN.EXE's Watcom routine-name records.

The game was built with Watcom's routine-name option (-en): every function is
preceded by its name, then one byte with the name's length, then the code:

    ... 63 68 65 63 6b 5f 66 6f 72 5f 63 64 0c | 53 51 52 ...
        c  h  e  c  k  _  f  o  r  _  c  d  12 | push ebx ...  (0x4013D0)

This scans the exe's code section (AUTO) for that pattern and writes:
  - a plain list, one "0x004013d0 check_for_cd" line per function, and
  - a Ghidra script (Jython, Script Manager > Run) that creates a function at
    each address and names it.

Only names and addresses are written (format knowledge and lists of function
names are allowed by CONTRIBUTING.md); no bytes of the exe. The exe itself and
the generated lists are never committed (.gitignore: *.txt under tools/out/).

Usage: python3 watcom_names.py NBAWIN.EXE [outdir]
Checks the exe is the v1.1 reference (size and SHA-256) and the three spot
checks from the stage 1 brief before writing anything.
"""
import hashlib
import os
import re
import struct
import sys

REF_SIZE = 2488320
REF_SHA256 = "3563b929b75379df3d93468d1c957b742f17b2a708098b7cfbeeac3fda51287d"
SPOT = {0x4013D0: "check_for_cd", 0x405890: "camera_setframerate", 0x4AE0E0: "drawshadows3rash"}
IDENT = re.compile(rb"[A-Za-z_][A-Za-z0-9_]*\Z")
IDCHAR = set(b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_")


def sections(d):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    optsz = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    out = []
    for i in range(nsec):
        o = pe + 24 + optsz + 40 * i
        name = d[o:o + 8].rstrip(b"\0").decode("latin-1")
        va, rsize, rptr = struct.unpack_from("<I", d, o + 12)[0], *struct.unpack_from("<II", d, o + 16)
        out.append((name, base + va, rptr, rsize))
    return out


# Watcom pads between functions with do-nothing instructions; a short (2 or 3
# character) name is only taken when such padding or the end of the previous
# function (ret, jmp) sits right before it, because random code bytes often look
# like a two-letter identifier followed by its length.
PAD_END = (b"\x90", b"\xc3", b"\xcc")
PAD_TAILS = (b"\x8b\xc0", b"\x8b\xc9", b"\x8b\xd2", b"\x8b\xdb", b"\x8b\xf6", b"\x8b\xff", b"\x8b\xe4", b"\x8b\xed",
             b"\x8d\x40\x00", b"\x8d\x49\x00", b"\x8d\x52\x00", b"\x8d\x5b\x00", b"\x8d\x76\x00", b"\x8d\x7f\x00",
             b"\x8d\x44\x20\x00", b"\x8d\x54\x22\x00",
             b"\x8d\x80\x00\x00\x00\x00", b"\x8d\x89\x00\x00\x00\x00", b"\x8d\x92\x00\x00\x00\x00",
             b"\x8d\x9b\x00\x00\x00\x00", b"\x8d\xb6\x00\x00\x00\x00", b"\x8d\xbf\x00\x00\x00\x00")


def padded(d, start):
    before = d[start - 8:start]
    return before.endswith(PAD_END) or before.endswith(PAD_TAILS) or before[-5:-4] == b"\xe9" or before[-2:-1] == b"\xeb"


def scan(d):
    auto = [s for s in sections(d) if s[0] == "AUTO"]
    if not auto:
        sys.exit("no AUTO section: not a Watcom exe")
    _, va0, raw, size = auto[0]
    names = {}
    for p in range(raw + 2, raw + size):
        n = d[p - 1]
        if n < 2 or n > 96 or p - 1 - n < raw:
            continue
        name = d[p - 1 - n:p - 1]
        if not IDENT.match(name):
            continue
        if d[p - 2 - n] in IDCHAR:      # part of a longer string: not a name record
            continue
        if n < 4 and not padded(d, p - 1 - n):
            continue
        names[va0 + (p - raw)] = name.decode("ascii")
    return names


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    d = open(sys.argv[1], "rb").read()
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")
    if len(d) != REF_SIZE or hashlib.sha256(d).hexdigest() != REF_SHA256:
        sys.exit("not the v1.1 NBAWIN.EXE (2,488,320 bytes, SHA-256 3563b929...): addresses would not match")
    names = scan(d)
    for va, want in SPOT.items():
        if names.get(va) != want:
            sys.exit("spot check failed at 0x%08X: expected %s, found %s" % (va, want, names.get(va)))
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "nba99_functions.txt"), "w", newline="\n") as f:
        for va in sorted(names):
            f.write("0x%08x %s\n" % (va, names[va]))
    with open(os.path.join(out, "nba99_name_functions.py"), "w", newline="\n") as f:
        f.write("# Ghidra script: names the NBA Live 99 v1.1 NBAWIN.EXE functions from their\n"
                "# Watcom routine-name records (generated by tools/watcom_names.py).\n"
                "# @category NBA99\n"
                "from ghidra.program.model.symbol import SourceType\n"
                "from ghidra.app.cmd.disassemble import DisassembleCommand\n"
                "NAMES = [\n")
        for va in sorted(names):
            f.write("    (0x%08x, %r),\n" % (va, names[va]))
        f.write("]\n"
                "fm = currentProgram.getFunctionManager()\n"
                "made = renamed = 0\n"
                "for va, name in NAMES:\n"
                "    a = toAddr(va)\n"
                "    fn = fm.getFunctionAt(a)\n"
                "    if fn is None:\n"
                "        DisassembleCommand(a, None, True).applyTo(currentProgram, monitor)\n"
                "        fn = createFunction(a, name)\n"
                "        if fn is not None: made += 1\n"
                "    if fn is not None:\n"
                "        fn.setName(name, SourceType.USER_DEFINED)\n"
                "        renamed += 1\n"
                "print('NBA99 names: %d functions named, %d created' % (renamed, made))\n")
    print("%d names, spot checks ok; written to %s" % (len(names), out))


if __name__ == "__main__":
    main()
